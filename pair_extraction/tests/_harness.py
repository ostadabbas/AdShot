def parse_shotsplit(x):
    """shotsplit is stored as a str repr of a python list, e.g. '[12, 30, ...]'."""
    import ast
    return x if isinstance(x, list) else ast.literal_eval(x)


def load_shotsplits(json_path):
    """Read a *_shotsplits.json (JSONL) -> {ad_id: parsed shotsplit list}."""
    import pandas as pd
    df = pd.read_json(json_path, lines=True)
    df = df.drop_duplicates("ad_id", keep="first")
    return {r["ad_id"]: parse_shotsplit(r["shotsplit"]) for _, r in df.iterrows()}


def cosine(a, b):
    import numpy as np
    a = np.asarray(a, dtype="float64").ravel()
    b = np.asarray(b, dtype="float64").ravel()
    denom = (np.linalg.norm(a) * np.linalg.norm(b)) or 1.0
    return float(np.dot(a, b) / denom)


def load_h5_embeddings(h5_path):
    """Return {shot_id: embedding vector} from an embeddings .h5."""
    import h5py
    out = {}
    with h5py.File(h5_path, "r") as hf:
        embs = hf["embeddings"][:]
        ids = [s.decode("ascii") for s in hf["shot_ids"][:]]
    for sid, emb in zip(ids, embs):
        out[sid] = emb
    return out


def compare_embeddings(produced, reference, floor=COSINE_FLOOR, only_prefix=None):
    """
    Compare two {shot_id: vector} dicts on their shared shot_ids.
    Returns (n_compared, min_cosine, mean_cosine). Raises if any pair < floor.
    """
    import numpy as np
    keys = set(produced) & set(reference)
    if only_prefix is not None:
        keys = {k for k in keys if k.startswith(only_prefix)}
    check(keys, f"no overlapping shot_ids to compare (prefix={only_prefix})")
    sims = []
    for k in sorted(keys):
        s = cosine(produced[k], reference[k])
        sims.append(s)
        check(s >= floor, f"shot {k}: cosine {s:.6f} < floor {floor}")
    return len(sims), float(np.min(sims)), float(np.mean(sims))


def keyframe_names(directory, prefix=None):
    """Set of keyframe filenames in a dir, optionally filtered by ad-id prefix."""
    if not os.path.isdir(directory):
        return set()
    names = {f for f in os.listdir(directory) if f.lower().endswith(".jpg")}
    if prefix is not None:
        names = {f for f in names if f.startswith(prefix)}
    return names


def md5(path):
    import hashlib
    h = hashlib.md5()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def cluster_membership_labels(clusters_dict, shot_universe=None):
    """
    Convert a {cluster_id: [shot_ids]} mapping into (shots, labels) parallel
    lists over the sorted union of shots, for adjusted_rand_score comparison.
    """
    shot_to_label = {}
    for label, shots in clusters_dict.items():
        for s in shots:
            shot_to_label[s] = str(label)
    shots = sorted(shot_to_label) if shot_universe is None else sorted(shot_universe)
    labels = [shot_to_label.get(s, "<none>") for s in shots]
    return shots, labels
