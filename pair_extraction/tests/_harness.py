class SkipTest(Exception):
    """Raise to mark a test as skipped (not built yet, missing input, no GPU)."""


def check(cond, msg):
    """Assert helper with a message; raises AssertionError on failure."""
    if not cond:
        raise AssertionError(msg)


def require(path, what="input"):
    """Skip (not fail) when a required reference/input path is missing."""
    if not os.path.exists(path):
        raise SkipTest(f"missing {what}: {path}")
    return path


def module_available(name):
    """True if an importable module of this name exists on sys.path."""
    try:
        return importlib.util.find_spec(name) is not None
    except (ImportError, ValueError):
        return False


def require_module(name, step_desc):
    """Skip when a stage module isn't built yet."""
    if not module_available(name):
        raise SkipTest(f"{name} not built yet ({step_desc})")


