"""
Shared test harness for the pair_extraction pipeline.

Provides:
  - Path/constant fixtures (reference artifacts, the canonical test brand).
  - Comparison helpers (exact for deterministic outputs, tolerant for the
    GPU/CPU float drift that shows up in embeddings / DBSCAN clustering).
  - A tiny runner protocol: every test module exposes a `META` dict and a
    `run()` function. `run()` returns None on success, raises `SkipTest` to
    skip (e.g. a not-yet-built stage or a missing video), and raises any other
    exception (typically AssertionError via `check`) on failure.

Design note: each stage test feeds the *reference inputs* into the stage under
test wherever possible, so float drift from an earlier stage never compounds
into a later stage's comparison. The one exception is the Stage-1 driver test
(step 5), which is an end-to-end integration test by definition.
"""

